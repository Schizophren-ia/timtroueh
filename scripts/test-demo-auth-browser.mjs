import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { mkdirSync } from 'node:fs';

const base = process.env.TEST_BASE_URL || 'http://127.0.0.1:5173';
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
try {
  mkdirSync('outputs', { recursive: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const email = `demo-ui-${Date.now()}@st.ueh.edu.vn`;
  await page.goto(base + '/account');
  await page.getByRole('button', { name: 'Đăng ký', exact: true }).click();
  await page.getByLabel('Họ và tên', { exact: true }).fill('Sinh viên Demo');
  await page.getByLabel('Email sinh viên UEH').fill('demo@gmail.com');
  await page.getByRole('button', { name: 'Nhận mã OTP mô phỏng' }).click();
  await page.getByRole('alert').filter({ hasText: 'đúng đuôi' }).waitFor();
  await page.getByLabel('Email sinh viên UEH').fill(email);
  const requested = page.waitForResponse(r => r.url().endsWith('/api/demo-auth/request-otp') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Nhận mã OTP mô phỏng' }).click();
  const issuedAt = Date.now(); assert.equal((await requested).status(), 200);
  const mailbox = page.getByTestId('demo-otp'); await mailbox.waitFor();
  const code = (await mailbox.textContent()).trim(); assert.match(code, /^\d{6}$/);
  assert.equal(await page.getByRole('button', { name: /Gửi lại mã sau/ }).isDisabled(), true);
  await page.getByLabel('Mã OTP 6 chữ số').fill(String((Number(code) + 1) % 1000000).padStart(6, '0'));
  await page.getByRole('button', { name: 'Xác minh và tạo tài khoản' }).click();
  await page.getByRole('alert').filter({ hasText: 'Mã sai' }).waitFor();
  await page.screenshot({ path: 'outputs/otp-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: 'outputs/otp-mobile.png', fullPage: true });
  await page.getByLabel('Mã OTP 6 chữ số').fill(code);
  await page.getByRole('button', { name: 'Xác minh và tạo tài khoản' }).click();
  await page.getByRole('heading', { name: 'Thông tin cá nhân' }).waitFor();
  assert.match(await page.locator('.auth-profile-note').textContent(), /mô phỏng/);
  const session = await (await context.request.get(base + '/api/session')).json();
  assert.equal(session.user.email, email); assert.equal(session.user.role, 'student');
  assert.equal((await context.request.get(base + '/api/admin/users')).status(), 403);
  await page.reload(); await page.getByRole('heading', { name: 'Thông tin cá nhân' }).waitFor();
  await page.goto(base + '/rooms/room-1');
  await page.getByRole('button', { name: 'Lưu phòng', exact: true }).click();
  await page.getByRole('button', { name: 'Đã lưu', exact: true }).waitFor();
  await page.goto(base + '/account');
  await page.getByRole('button', { name: 'Đăng xuất', exact: true }).click();
  await page.getByRole('button', { name: 'Đăng nhập', exact: true }).waitFor();
  assert.equal((await (await context.request.get(base + '/api/session')).json()).user, null);
  // Reuse the actual cooldown rather than a client-side or server-side test bypass.
  const wait = Math.max(0, issuedAt + 61000 - Date.now());
  console.log('Registration, invalid code, mobile layout, persistence, favorites, permissions and logout passed. Cooldown wait:', wait);
  await new Promise(resolve => setTimeout(resolve, wait));
  await page.getByLabel('Email sinh viên UEH').fill(email);
  await page.getByRole('button', { name: 'Nhận mã OTP mô phỏng' }).click();
  await mailbox.waitFor();
  await page.getByLabel('Mã OTP 6 chữ số').fill((await mailbox.textContent()).trim());
  await page.getByRole('button', { name: 'Xác minh và đăng nhập' }).click();
  await page.getByRole('heading', { name: 'Thông tin cá nhân' }).waitFor();
  const restored = await (await context.request.get(base + '/api/session')).json();
  assert.equal(restored.user.id, session.user.id);
  assert.equal((await (await context.request.get(base + '/api/rooms?favorites=1')).json()).rooms.length, 1);
  await context.request.delete(base + '/api/favorites/room-1');
  await context.request.post(base + '/api/demo-auth/logout');
  assert.deepEqual(errors, []);
  console.log('PASS: full demo OTP register/login flow, no browser errors.');
} finally { await browser.close(); }
